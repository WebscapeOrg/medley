const assert = require('node:assert/strict');

module.exports = async function checkMuteHierarchy(page, base, token, custom) {
  const headers = {'X-Medley-Token': token};
  const api = async () => (await (await page.request.get(base + '/api', {headers})).json());
  const original = (await api()).settings;
  const all = page.locator('#workspace-mute');
  const done = page.locator('#mute-done');
  const statusButtons = page.locator('.rule-actions button:first-child');
  const lowerButtons = page.locator('#workspace-mute,.rule-actions button:first-child');
  const muted = async () => page.getByText('Muted. Saved sound choices are kept.', {exact: true}).waitFor();
  const unmuted = async () => page.getByText('Unmuted. Saved sound choices restored.', {exact: true}).waitFor();
  const globallyUnmuted = async () => page.getByText('Unmuted. Workspace sounds play again.', {exact: true}).waitFor();
  const refresh = async () => {
    await page.locator('#refresh').click();
    await page.getByText('Workspaces refreshed.', {exact: true}).waitFor();
  };
  const disabled = async (buttons, value) => assert.deepEqual(await buttons.evaluateAll(els => els.map(el => el.disabled)), Array(await buttons.count()).fill(value));

  await done.click();
  await muted();
  const individualMute = (await api()).settings;
  await disabled(statusButtons, false);
  await page.locator('#mute-length').selectOption('0');
  await page.locator('#mute').click();
  await page.getByText('Muted until unmuted.', {exact: true}).waitFor();
  await disabled(lowerButtons, true);
  assert.equal(await page.locator('#mute').isEnabled(), true);
  assert.equal(await all.getAttribute('title'), 'Unmute workspace sounds first.');
  assert.equal(await done.evaluate(el => getComputedStyle(el).cursor), 'default');
  assert.deepEqual((await api()).settings, individualMute);
  let muteRequests = 0;
  const countMuteRequests = request => {if (request.url().endsWith('/status-mute')) muteRequests++;};
  page.on('request', countMuteRequests);
  await lowerButtons.evaluateAll(els => els.forEach(el => el.click()));
  assert.equal(muteRequests, 0);
  page.off('request', countMuteRequests);

  await page.locator('#workspace').focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('#status-idle').evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button', {name: 'Preview Idle sound', exact: true}).evaluate(el => el === document.activeElement), true);
  await page.reload();
  await done.waitFor();
  await disabled(lowerButtons, true);
  await page.locator('#workspace').selectOption('w2');
  await disabled(lowerButtons, true);
  await refresh();
  await disabled(lowerButtons, true);
  await page.locator('#workspace').selectOption('w1');
  await page.getByRole('button', {name: 'Preview Done sound', exact: true}).click();
  await page.getByText('This sound is set to quiet.', {exact: true}).waitFor();
  await disabled(lowerButtons, true);
  await page.locator('#reset').click();
  await page.getByText('All sounds reset to default. You can undo this reset.', {exact: true}).waitFor();
  await disabled(lowerButtons, true);
  await page.locator('#undo').click();
  await page.getByText('Previous sound choices restored.', {exact: true}).waitFor();
  await disabled(lowerButtons, true);
  assert.deepEqual((await api()).settings, individualMute);

  await page.route('**/unmute', route => route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({error: 'Could not unmute. Try again.'})}));
  await page.locator('#mute').click();
  await page.getByText('Could not unmute. Try again.', {exact: true}).waitFor();
  await disabled(lowerButtons, true);
  assert.equal(await page.locator('#mute').isEnabled(), true);
  await page.unroute('**/unmute');
  await refresh();
  await page.setViewportSize({width: 1600, height: 1000});
  await page.screenshot({path: 'docs/mute-global.png', fullPage: true});

  await page.locator('#mute').click();
  await globallyUnmuted();
  await disabled(lowerButtons, false);
  assert.equal(await done.textContent(), 'Unmute');
  assert.equal(await page.locator('#status-done').isDisabled(), true);
  assert.deepEqual((await api()).settings, individualMute);
  await all.click();
  await muted();
  await disabled(statusButtons, true);
  assert.equal(await all.isEnabled(), true);
  assert.equal(await done.getAttribute('title'), 'Unmute this workspace first.');
  await page.screenshot({path: 'docs/mute-workspace.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 1000});
  await page.emulateMedia({colorScheme: 'dark', reducedMotion: 'reduce'});
  await page.screenshot({path: 'docs/mute-hierarchy-mobile.png', fullPage: true});
  await page.emulateMedia({colorScheme: 'light'});
  await page.setViewportSize({width: 1280, height: 1000});
  await page.locator('#workspace').selectOption('w2');
  await disabled(statusButtons, false);
  await page.locator('#workspace').selectOption('w1');
  await disabled(statusButtons, true);
  await page.reload();
  await done.waitFor();
  await disabled(statusButtons, true);
  await page.locator('#mute-length').selectOption('0');
  await page.locator('#mute').click();
  await page.getByText('Muted until unmuted.', {exact: true}).waitFor();
  await disabled(lowerButtons, true);
  await page.locator('#mute').click();
  await globallyUnmuted();
  assert.equal(await all.isEnabled(), true);
  await disabled(statusButtons, true);
  await all.focus();
  await page.keyboard.press('Enter');
  await unmuted();
  await disabled(statusButtons, false);
  assert.equal(await all.evaluate(el => el === document.activeElement), true);
  assert.equal(await page.locator('#status-done').inputValue(), custom);
  assert.deepEqual((await api()).settings.rules, original.rules);

  for (const status of (await api()).statuses) {
    await page.locator('#mute-' + status).focus();
    await page.keyboard.press('Space');
    await muted();
  }
  await disabled(statusButtons, true);
  assert.equal(await all.evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Enter');
  await unmuted();
  await disabled(statusButtons, false);

  await done.click();
  await muted();
  await page.request.post(base + '/mute', {headers, data: {minutes: 1}});
  await page.route('**/api', async route => {
    const response = await route.fetch();
    const data = await response.json();
    data.mute.until = Date.now() / 1000 + 2;
    await route.fulfill({response, json: data});
  });
  await refresh();
  await page.unroute('**/api');
  await disabled(lowerButtons, true);
  await page.request.post(base + '/unmute', {headers, data: {}});
  let releasePreview;
  const previewGate = new Promise(resolve => {releasePreview = resolve;});
  await page.route('**/preview', async route => {await previewGate; await route.continue();});
  await page.getByRole('button', {name: 'Preview Working sound', exact: true}).click();
  await page.getByText('Loading preview…', {exact: true}).waitFor();
  await page.waitForFunction(() => document.getElementById('mute').textContent === 'Mute');
  await disabled(lowerButtons, true);
  releasePreview();
  await page.getByText('This sound is set to quiet.', {exact: true}).waitFor();
  await page.unroute('**/preview');
  await disabled(lowerButtons, false);
  assert.equal(await done.textContent(), 'Unmute');
  assert.equal(await page.locator('#status-done').isDisabled(), true);
  await done.click();
  await unmuted();
  assert.deepEqual((await api()).settings, original);
  assert.equal((await api()).mute, null);
};
